package krl

import (
	"bytes"
	"context"
	"errors"
	"fmt"
	"io/fs"
	"net/http"
	"os"
	"time"

	"codeberg.org/sdassow/atomic"
	"github.com/andrewheberle/ssh-ca-client/internal/pkg/api"
	"github.com/andrewheberle/ssh-ca-client/internal/pkg/httpclient"
	sshkrl "github.com/forfuncsake/krl"
	"github.com/hiddeco/sshsig"
	"golang.org/x/crypto/ssh"
)

// Namespace is the SSHSIG namespace the CA signs KRLs with
const Namespace = "krl@com.github.serverless-ssh-ca.andrewheberle"

// FileMode is the mode of an installed KRL
const FileMode fs.FileMode = 0440

// CertificateType is the type of certificate a KRL revokes
type CertificateType string

const (
	// User is the KRL for user certificates
	User CertificateType = "user"

	// Host is the KRL for host certificates
	Host CertificateType = "host"
)

var (
	// ErrInvalidSignature is returned when the signature on the KRL cannot be
	// decoded or does not verify with the CA public key
	ErrInvalidSignature = errors.New("krl signature verification failed")

	// ErrNoPublicKey is returned when no CA public key is provided to verify
	// the signature on the KRL with
	ErrNoPublicKey = errors.New("no public key provided for signature verification")

	// ErrOlderKRL is returned when the KRL is older than an existing KRL
	ErrOlderKRL = errors.New("krl is older than the existing krl")

	// ErrUnexpectedCA is returned when a certificate section of the KRL is not
	// for the CA, including sections that apply to any CA
	ErrUnexpectedCA = errors.New("encountered krl certificate section with unexpected CA")

	// ErrUnexpectedSection is returned when the KRL contains a section that
	// does not revoke certificates, such as one revoking explicit keys
	ErrUnexpectedSection = errors.New("encountered unexpected section type in krl")
)

// Verified is a KRL whose signature has been verified with the CA public key
// and that only revokes certificates issued by that CA. It can only be
// obtained from [Fetch].
type Verified struct {
	raw    []byte
	parsed *sshkrl.KRL
}

// Fetch retrieves the KRL for certificatetype from server and verifies it
// with pub, which must be the public key of the CA. Requests use the client
// from [httpclient.New] unless opts sets another with [api.WithHTTPClient].
func Fetch(ctx context.Context, server string, certificatetype CertificateType, pub ssh.PublicKey, opts ...api.ClientOption) (*Verified, error) {
	// an unverifiable KRL is never useful, so do not request one
	if pub == nil {
		return nil, ErrNoPublicKey
	}

	res, err := get(ctx, server, certificatetype, opts...)
	if err != nil {
		return nil, fmt.Errorf("could not retrieve krl: %w", err)
	}

	parsed, err := verify(res, pub)
	if err != nil {
		return nil, err
	}

	return &Verified{raw: res.Krl, parsed: parsed}, nil
}

// Bytes returns the KRL in the format used by OpenSSH
func (v *Verified) Bytes() []byte {
	return bytes.Clone(v.raw)
}

// Version returns the version of the KRL
func (v *Verified) Version() uint64 {
	return v.parsed.Version
}

// Generated returns the time the KRL was generated by the CA
func (v *Verified) Generated() time.Time {
	return time.Unix(int64(v.parsed.GeneratedDate), 0).UTC()
}

// Sections returns the number of sections in the KRL
func (v *Verified) Sections() int {
	return len(v.parsed.Sections)
}

// Outcome is the result of a successful [Verified.Install]
type Outcome int

const (
	// Written means the KRL was written, replacing any older KRL
	Written Outcome = iota

	// Unchanged means the file already held the KRL with [FileMode], so it
	// was not written
	Unchanged

	// ReplacedUnparseable means the file held something that could not be
	// parsed as a KRL, so it was replaced
	ReplacedUnparseable
)

func (o Outcome) String() string {
	switch o {
	case Written:
		return "written"
	case Unchanged:
		return "unchanged"
	case ReplacedUnparseable:
		return "replaced unparseable"
	}

	return fmt.Sprintf("Outcome(%d)", int(o))
}

// Install atomically writes the KRL to path with [FileMode]. A KRL older than
// one already at path is never installed, so a previously issued KRL cannot
// un-revoke certificates; an error wrapping [ErrOlderKRL] is returned and
// the file is left alone. KRLs are compared by version and then by the date
// they were generated, as the CA does not increase the version for each KRL.
func (v *Verified) Install(path string) (Outcome, error) {
	outcome := Written

	existing, err := os.ReadFile(path)
	switch {
	case errors.Is(err, fs.ErrNotExist):
		// nothing to compare against
	case err != nil:
		return Written, fmt.Errorf("could not read existing krl: %w", err)
	case bytes.Equal(existing, v.raw):
		info, err := os.Stat(path)
		if err != nil {
			return Written, fmt.Errorf("could not check existing krl: %w", err)
		}
		if info.Mode().Perm() == FileMode {
			return Unchanged, nil
		}
	default:
		current, err := sshkrl.ParseKRL(existing)
		if err != nil {
			outcome = ReplacedUnparseable
			break
		}
		if v.olderThan(current) {
			return Written, fmt.Errorf("%w: got version %d generated at %d, existing is version %d generated at %d",
				ErrOlderKRL, v.parsed.Version, v.parsed.GeneratedDate, current.Version, current.GeneratedDate)
		}
	}

	if err := atomic.WriteFile(path, bytes.NewReader(v.raw), atomic.FileMode(FileMode)); err != nil {
		return Written, fmt.Errorf("could not write krl: %w", err)
	}

	return outcome, nil
}

func (v *Verified) olderThan(current *sshkrl.KRL) bool {
	k := v.parsed

	return k.Version < current.Version || (k.Version == current.Version && k.GeneratedDate < current.GeneratedDate)
}

// get retrieves the KRL and its signature for certificatetype from server
func get(ctx context.Context, server string, certificatetype CertificateType, opts ...api.ClientOption) (*api.KeyRevocationListResponse, error) {
	// options are applied in order, so any client in opts replaces the default
	opts = append([]api.ClientOption{api.WithHTTPClient(httpclient.New())}, opts...)
	client, err := api.NewClientWithResponses(server, opts...)
	if err != nil {
		return nil, fmt.Errorf("creating api client: %w", err)
	}

	var (
		statusCode  int
		body        []byte
		contentType string
		list        *api.KeyRevocationListResponse
	)
	switch certificatetype {
	case User:
		res, err := client.GetUserRevocationListWithResponse(ctx)
		if err != nil {
			return nil, fmt.Errorf("requesting krl: %w", err)
		}
		statusCode, body, contentType, list = res.StatusCode(), res.Body, res.ContentType(), res.JSON200
	case Host:
		res, err := client.GetHostRevocationListWithResponse(ctx)
		if err != nil {
			return nil, fmt.Errorf("requesting krl: %w", err)
		}
		statusCode, body, contentType, list = res.StatusCode(), res.Body, res.ContentType(), res.JSON200
	default:
		return nil, fmt.Errorf("unsupported certificate type: %q", certificatetype)
	}

	if statusCode != http.StatusOK {
		return nil, api.StatusError(statusCode, body)
	}

	if list == nil {
		return nil, fmt.Errorf("unexpected response content type: %q", contentType)
	}

	return list, nil
}

// verify checks the signature on the KRL using pub, then parses it and
// checks it only contains certificate sections for that CA. The signature is
// checked before the KRL is parsed.
func verify(res *api.KeyRevocationListResponse, pub ssh.PublicKey) (*sshkrl.KRL, error) {
	// unarmor and verify signature
	sig, err := sshsig.Unarmor([]byte(res.Signature))
	if err != nil {
		return nil, fmt.Errorf("%w: problem unarmoring signature: %w", ErrInvalidSignature, err)
	}

	if err := sshsig.Verify(bytes.NewReader(res.Krl), sig, pub, sshsig.HashSHA512, Namespace); err != nil {
		return nil, fmt.Errorf("%w: %w", ErrInvalidSignature, err)
	}

	parsedKrl, err := sshkrl.ParseKRL(res.Krl)
	if err != nil {
		return nil, fmt.Errorf("problem parsing krl: %w", err)
	}

	// check that all sections revoke certificates
	for _, section := range parsedKrl.Sections {
		if _, ok := section.(*sshkrl.KRLCertificateSection); !ok {
			return nil, ErrUnexpectedSection
		}
	}

	// check that all sections are for our CA
	pubBytes := pub.Marshal()
	for _, section := range parsedKrl.Sections {
		// a nil CA applies the section to certificates from any CA
		s := section.(*sshkrl.KRLCertificateSection)
		if s.CA == nil || !bytes.Equal(s.CA.Marshal(), pubBytes) {
			return nil, ErrUnexpectedCA
		}
	}

	return parsedKrl, nil
}
